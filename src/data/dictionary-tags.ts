export function isPartOfSpeechTag(code: string): boolean {
  return code in partsOfSpeech || /^v[245][a-z]+$/.test(code);
}
export function dictionaryTagLabel(code: string): string {
  if (labels[code]) return labels[code];
  const verb = /^v([245])([a-z])([ks])?$/.exec(code);
  if (verb)
    return `${verb[1] === "5" ? "Godan" : verb[1] === "4" ? "Classical yodan" : "Classical nidan"} verb in -${endings[verb[2]] || verb[2]}${verb[1] === "2" ? ` (${verb[3] === "k" ? "upper" : "lower"} class)` : ""}`;
  return code;
}
